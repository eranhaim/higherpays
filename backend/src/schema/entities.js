// One in-app event. accountId and agentId narrow who should see it.
const Notification = entity('notifications', {
  fields: {
    id:                uuid().primaryKey(),
    workspaceId:       uuid().references('workspaces').notNull(),
    event:             text().notNull(),        // e.g. 'payment.paid'
    title:             text().notNull(),
    body:              text(),
    amount:            money(),
    currency:          char(3),
    entityType:        text(),
    entityId:          uuid(),
    accountId:         uuid().references('accounts', 'SET NULL'),
    agentId:           uuid().references('agents', 'SET NULL'),
  },
  indexes: [{ columns: ['workspaceId', 'createdAt'] }],
  timestamps: 'created',
});

const NotificationRead = entity('notification_reads', {
  fields: {
    workspaceId:    uuid().references('workspaces').notNull(),
    notificationId: uuid().references('notifications').notNull(),
    userId:         uuid().references('users').notNull(),
    readAt:         timestamp().notNull().default('now()'),
  },
  primaryKey: ['notificationId', 'userId'],
});

// Where a workspace forwards events outside the app.
const NotificationChannel = entity('notification_channels', {
  fields: {
    id:              uuid().primaryKey(),
    workspaceId:     uuid().references('workspaces').notNull(),
    type:            enumOf(CHANNEL_TYPE).notNull(),
    target:          text().notNull(),          // chat id, for telegram
    label:           text(),
    events:          textArray().notNull().default("ARRAY['payment.paid']"),
    active:          bool().notNull().default('true'),
    lastError:       text(),
    lastSentAt:      timestamp(),
    createdByUserId: uuid().references('users', 'SET NULL'),
  },
  unique: [['workspaceId', 'type', 'target']],
  timestamps: 'created',
});

// Which events one user wants, in one workspace.
const NotificationPreference = entity('notification_preferences', {
  fields: {
    workspaceId: uuid().references('workspaces').notNull(),
    userId:      uuid().references('users').notNull(),
    events:      textArray().notNull()
      .default("ARRAY['payment.paid','payment.failed','payment.refunded','payment.chargeback','payout.paid']"),
    updatedAt:   timestamp().notNull().default('now()'),
  },
  primaryKey: ['workspaceId', 'userId'],
});

// Idempotent inbox for provider callbacks. workspaceId is null until the
// payload is resolved to a workspace.
const WebhookEvent = entity('webhook_events', {
  fields: {
    id:              uuid().primaryKey(),
    workspaceId:     uuid().references('workspaces', 'SET NULL'),
    provider:        text().notNull(),
    eventType:       text(),
    providerEventId: text(),
    signatureValid:  bool(),
    processed:       bool().notNull().default('false'),
    payload:         jsonb().notNull(),
    receivedAt:      timestamp().notNull().default('now()'),
    processedAt:     timestamp(),
  },
  unique: [['provider', 'providerEventId']],
  indexes: [{ columns: ['processed'], where: 'processed = false' }],
});

// Append-only record of actions and PII access.
const AuditLog = entity('audit_log', {
  fields: {
    id:          bigIdentity(),
    workspaceId: uuid().references('workspaces', 'SET NULL'),
    actorUserId: uuid().references('users', 'SET NULL'),
    action:      text().notNull(),              // e.g. 'customer.export', 'link.create'
    entityType:  text(),
    entityId:    uuid(),
    metadata:    jsonb().notNull().default("'{}'::jsonb"),
    ip:          inet(),
  },
  indexes: [
    { columns: ['workspaceId', 'createdAt'] },
    { columns: ['actorUserId', 'createdAt'] },
  ],
  timestamps: 'created',
});

