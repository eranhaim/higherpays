// Effective-dated per-event fees the PSP charges on settlement. Set by the
// platform, not by the workspace.
const SettlementFeeConfig = entity('settlement_fee_config', {
  fields: {
    id:                 uuid().primaryKey(),
    workspaceId:        uuid().references('workspaces').notNull(),
    chargebackFee:      money().notNull().default('0'),
    refundFee:          money().notNull().default('0'),
    declineFee:         money().notNull().default('0'),
    settlementFeePct:   percent().notNull().default('0'),
    settlementFeeFlat:  money().notNull().default('0'),
    reservePct:         percent().notNull().default('0'),
    reserveReleaseDays: int().notNull().default('0'),
    effectiveFrom:      timestamp().notNull().default('now()'),
    createdByUserId:    uuid().references('users', 'SET NULL'),
  },
  indexes: [{ columns: ['workspaceId', 'effectiveFrom'] }],
  timestamps: 'created',
});

// One settlement report from the provider, imported as-is. Four decimals
// because the provider's own figures carry them.
const Settlement = entity('settlements', {
  fields: {
    id:                uuid().primaryKey(),
    workspaceId:       uuid().references('workspaces').notNull(),
    currency:          char(3).notNull(),
    periodStart:       date().notNull(),
    periodEnd:         date().notNull(),
    settlementDate:    date(),
    paid:              bool().notNull().default('false'),

    totalTransactions: int().notNull().default('0'),
    refunds:           int().notNull().default('0'),
    chargebacks:       int().notNull().default('0'),
    declined:          int().notNull().default('0'),

    volume:            numeric(16, 4).notNull().default('0'),
    approvedCost:      numeric(16, 4).notNull().default('0'),
    declineCost:       numeric(16, 4).notNull().default('0'),
    refundCost:        numeric(16, 4).notNull().default('0'),
    chargebackCost:    numeric(16, 4).notNull().default('0'),
    mdr:               numeric(16, 4).notNull().default('0'),
    volumeFee:         numeric(16, 4).notNull().default('0'),
    reserve:           numeric(16, 4).notNull().default('0'),   // held this period
    totalFees:         numeric(16, 4).notNull().default('0'),
    net:               numeric(16, 4).notNull().default('0'),
    debit:             numeric(16, 4).notNull().default('0'),   // carried forward
    credit:            numeric(16, 4).notNull().default('0'),   // due to be paid out

    reportSettings:    jsonb(),                 // fee rates printed in the report header
    sourceFile:        text(),
    importedByUserId:  uuid().references('users', 'SET NULL'),
    importedAt:        timestamp().notNull().default('now()'),
  },
  unique: [['workspaceId', 'currency', 'periodStart', 'periodEnd']],
  indexes: ['workspaceId'],
});

// ===========================================================================
// Operations
